/**
 * The cabin in five more languages.
 *
 * Separate from i18n.ts because that file is the dictionary's structure and
 * this one is its contents: the English and the Chinese are written as pairs
 * up there because they were written together, and everything since is laid
 * over them one language at a time.
 *
 * ── How these are written ──────────────────────────────────────────────────
 * The English in this cabin is short, concrete and never explains itself, and
 * that is the thing being translated — not the words. "Touch anywhere to
 * begin" is four words because a placard is four words, so the French is
 * "Touchez l'écran pour commencer" and not a sentence about what will happen
 * when you do. Where a language's idiom for a seat-back screen differs from
 * the English, the idiom wins.
 *
 * Units and abbreviations follow local aviation usage: "V/S" stays, because
 * it is on the instrument in every cabin in the world; "ft" and "kt" stay for
 * the same reason.
 *
 * ── What is not here ───────────────────────────────────────────────────────
 * Content. Dish names, drink names, the films' own synopses, the quiz's
 * questions and the cities' names carry their own translations in their own
 * files, and where they have none they fall back to English on purpose: a
 * menu is written, not translated by whoever is nearest.
 *
 * ── What these need ────────────────────────────────────────────────────────
 * A reader. These were written in one pass by somebody who is fluent in none
 * of them, against an English original that has been argued over line by
 * line. They are better than an untranslated screen and they are not a
 * native's copy; the tone in particular — this cabin never says "please" and
 * never apologises — is the first thing a pass should check.
 *
 * ── Why a table rather than a call ─────────────────────────────────────────
 * This file used to call `speak()` from i18n at module scope, which made the
 * two modules circular: i18n imported this one for its side effect, this one
 * ran before i18n had finished initialising, and the first thing it touched
 * was a `const` still in its temporal dead zone. The whole cabin failed to
 * boot with "Cannot access 'OVERLAY' before initialization" — a blank screen
 * from an import order.
 *
 * Now the dependency runs one way: this file builds a table and exports it,
 * i18n reads the table. The only thing it takes from i18n is a type, which
 * is erased before any of this runs.
 */

const TABLE: Partial<Record<Lang, Partial<Record<Key, string>>>> = {};
const speak = (lang: Lang, words: Partial<Record<Key, string>>) => {
  TABLE[lang] = words;
};

